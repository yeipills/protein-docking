//! Triangle mesh of a molecular surface, the common currency between surface sources
//! (MSMS files, the built-in SES generator) and consumers (context shapes, docking, viewer).

use crate::error::Result;
use crate::geom::vec3::*;
use crate::io::msms::MsmsSurface;

#[derive(Debug, Clone, Default)]
pub struct Mesh {
    pub vertices: Vec<V3>,
    /// Unit outward normal per vertex.
    pub normals: Vec<V3>,
    /// 0-based vertex indices, counter-clockwise seen from outside.
    pub faces: Vec<[u32; 3]>,
}

impl Mesh {
    pub fn from_msms(s: &MsmsSurface) -> Result<Mesh> {
        let mut faces = s.faces()?;
        crate::geom::sdf::orient_outward(&s.vertices, &s.normals, &mut faces);
        Ok(Mesh {
            vertices: s.vertices.clone(),
            normals: s.normals.clone(),
            faces,
        })
    }

    /// MSMS-style surface (1-based faces, all face types 0) so the context-shape pipelines
    /// can consume any mesh.
    pub fn to_msms(&self) -> MsmsSurface {
        MsmsSurface {
            vertices: self.vertices.clone(),
            normals: self.normals.clone(),
            faces_raw: self.faces.iter().map(|f| f.map(|i| i + 1)).collect(),
            face_types: vec![0; self.faces.len()],
        }
    }

    pub fn area(&self) -> f64 {
        self.faces
            .iter()
            .map(|f| {
                let [a, b, c] = f.map(|i| self.vertices[i as usize]);
                0.5 * norm(cross(sub(b, a), sub(c, a)))
            })
            .sum()
    }

    /// Enclosed volume (divergence theorem); meaningful for closed, outward-oriented meshes.
    pub fn volume(&self) -> f64 {
        self.faces
            .iter()
            .map(|f| {
                let [a, b, c] = f.map(|i| self.vertices[i as usize]);
                dot(a, cross(b, c)) / 6.0
            })
            .sum()
    }

    /// MSMS `.vert` text (3 header lines, 1-based conventions).
    pub fn write_msms_vert(&self) -> String {
        use std::fmt::Write;
        let mut s = String::with_capacity(self.vertices.len() * 80);
        s.push_str("# vertices generated by cshape\n#vertex #sphere density probe_r\n");
        writeln!(
            s,
            "{:7} {:7} {:5.2} {:5.2}",
            self.vertices.len(),
            0,
            0.0,
            0.0
        )
        .unwrap();
        for (v, n) in self.vertices.iter().zip(&self.normals) {
            writeln!(
                s,
                "{:9.3} {:9.3} {:9.3} {:9.3} {:9.3} {:9.3} {:7} {:7} {:2}",
                v[0], v[1], v[2], n[0], n[1], n[2], 0, 0, 0
            )
            .unwrap();
        }
        s
    }

    /// MSMS `.face` text.
    pub fn write_msms_face(&self) -> String {
        use std::fmt::Write;
        let mut s = String::with_capacity(self.faces.len() * 40);
        s.push_str("# faces generated by cshape\n#faces #sphere density probe_r\n");
        writeln!(s, "{:7} {:7} {:5.2} {:5.2}", self.faces.len(), 0, 0.0, 0.0).unwrap();
        for f in &self.faces {
            writeln!(
                s,
                "{:6} {:6} {:6} {:2} {:6}",
                f[0] + 1,
                f[1] + 1,
                f[2] + 1,
                0,
                0
            )
            .unwrap();
        }
        s
    }
}
