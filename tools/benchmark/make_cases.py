#!/usr/bin/env python3
"""Convert the Docking Benchmark 5.5 case table (Table_BM5.5.xlsx) to tools/benchmark/cases.tsv.

Usage:
    python3 tools/benchmark/make_cases.py data/benchmark/Table_BM5.5.xlsx \
        [--structures data/benchmark/benchmark5.5/structures] > tools/benchmark/cases.tsv

Needs openpyxl. With --structures, checks that the four files of every case exist.

The `id` column is the prefix of the structure files. It is the complex PDB code except for
complexes that appear several times in the table with different chains; the benchmark
README names those files 9QFW, BAAD, BOYV, BP57 and CP57 (see RENAMED below).
"""

import argparse
import os
import sys

import openpyxl

# Complex column of the table -> structure file prefix, for the renamed duplicates (chains
# checked against the *_r_b / *_l_b files).
RENAMED = {
    "1OYV_B:I": "BOYV",
    "3AAD_A:D": "BAAD",
    "3P57_CD:P": "BP57",
    "3P57_IJ:P": "CP57",
}

CATEGORIES = {"Rigid-body": "rigid", "Medium Difficulty": "medium", "Difficult": "difficult"}

TYPES = {
    "AA": "antibody-antigen (unbound antibody)",
    "AS": "antibody-antigen (bound antibody)",
    "EI": "enzyme-inhibitor",
    "ES": "enzyme-substrate",
    "ER": "enzyme-regulatory/accessory chain",
    "OG": "other, G-protein",
    "OR": "other, receptor",
    "OX": "other, miscellaneous",
}

COLUMNS = [
    "id", "complex", "category", "type", "irmsd", "dasa", "version",
    "receptor", "receptor_name", "ligand", "ligand_name",
]


def clean(v):
    return " ".join(str(v).split()) if v is not None else ""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("xlsx")
    ap.add_argument("--structures", help="directory with XXXX_{r,l}_{u,b}.pdb to check")
    args = ap.parse_args()

    ws = openpyxl.load_workbook(args.xlsx, data_only=True).worksheets[0]
    rows, category = [], None
    for r in ws.iter_rows(values_only=True):
        first = clean(r[0])
        if not first:
            continue
        heading = first.split(" (")[0]
        if heading in CATEGORIES and r[1] is None:
            category = CATEGORIES[heading]
            continue
        if len(first) < 6 or first[4] != "_" or category is None:
            continue  # title and header lines
        complex_ = first.replace(" ", "")
        kind = clean(r[1])
        if kind not in TYPES:
            sys.exit(f"unknown complex type {kind!r} for {complex_}")
        version = r[8]
        version = str(int(version)) if float(version).is_integer() else str(version)
        rows.append({
            "id": RENAMED.get(complex_, complex_[:4]),
            "complex": complex_,
            "category": category,
            "type": kind,
            "irmsd": f"{float(r[6]):.2f}",
            "dasa": str(int(r[7])),
            "version": version,
            "receptor": clean(r[2]),
            "receptor_name": clean(r[3]),
            "ligand": clean(r[4]),
            "ligand_name": clean(r[5]),
        })

    ids = [r["id"] for r in rows]
    dup = sorted({i for i in ids if ids.count(i) > 1})
    if dup:
        sys.exit(f"duplicate case ids (extend RENAMED): {dup}")
    if args.structures:
        missing = [
            f"{i}_{p}.pdb" for i in ids for p in ("r_u", "l_u", "r_b", "l_b")
            if not os.path.exists(os.path.join(args.structures, f"{i}_{p}.pdb"))
        ]
        if missing:
            sys.exit(f"missing structure files: {missing}")

    out = sys.stdout
    out.write("# Protein-Protein Docking Benchmark 5.5 (Vreven et al., J Mol Biol 2015), from Table_BM5.5.xlsx.\n")
    out.write("# Generated by tools/benchmark/make_cases.py. category: rigid | medium | difficult;\n")
    out.write("# type: " + "; ".join(f"{k} {v}" for k, v in TYPES.items()) + ";\n")
    out.write("# irmsd: unbound-bound interface RMSD (A); dasa: buried surface area (A^2); version: BM version introduced.\n")
    out.write("\t".join(COLUMNS) + "\n")
    for r in rows:
        out.write("\t".join(r[c] for c in COLUMNS) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
