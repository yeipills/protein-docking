#!/usr/bin/env python3
"""Compare cs-core's docking metrics with the official DockQ program.

Usage:
    pip install DockQ            # official implementation (Mirabello & Wallner, v2)
    cargo run --release -p cs-core --example dockq_poses -- OUT data/complexes/1AHW/1AHW \
        data/benchmark/benchmark5.5/structures/BOYV ...
    python3 tools/benchmark/validate_dockq.py OUT [--dockq DockQ] [--fixture FILE]

Reads OUT/poses.tsv (written by the `dockq_poses` example), runs DockQ on every
OUT/<case>_pose<k>.pdb against OUT/<case>_native.pdb with the chain mapping fixed
(model A:B -> native A:B, i.e. receptor and ligand each merged into one chain), prints a
Markdown table with both sets of values and the largest differences, and optionally writes
a fixture with the poses and DockQ's values for crates/cs-core/tests/eval.rs.
"""

import argparse
import json
import os
import subprocess
import sys
import tempfile

FIELDS = ["fnat", "fnonnat", "irmsd", "lrmsd", "dockq"]
DOCKQ_KEYS = {"fnat": "fnat", "fnonnat": "fnonnat", "irmsd": "iRMSD", "lrmsd": "LRMSD", "dockq": "DockQ"}


def run_dockq(exe, model, native):
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, "out.json")
        subprocess.run(
            [exe, model, native, "--mapping", "AB:AB", "--json", out, "--short"],
            check=True,
            stdout=subprocess.DEVNULL,
        )
        with open(out) as f:
            result = json.load(f)["best_result"]["AB"]
    return {k: float(result[v]) for k, v in DOCKQ_KEYS.items()}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("dir", help="output directory of the dockq_poses example")
    ap.add_argument("--dockq", default="DockQ", help="DockQ executable (default: DockQ on PATH)")
    ap.add_argument("--fixture", help="write poses and DockQ values to this TSV")
    args = ap.parse_args()

    with open(os.path.join(args.dir, "poses.tsv")) as f:
        header = f.readline().rstrip("\n").split("\t")
        rows = [dict(zip(header, line.rstrip("\n").split("\t"))) for line in f if line.strip()]

    print("| case | pose | fnat (ours / DockQ) | fnonnat | iRMSD Å | LRMSD Å | DockQ | ours: exact coords / best mapping |")
    print("|---|---|---|---|---|---|---|---|")
    worst = {k: (0.0, None) for k in FIELDS}
    fixture = ["case\tpose\trot\ttrans\t" + "\t".join(FIELDS)]
    for r in rows:
        case, pose = r["case"], r["pose"]
        ref = run_dockq(
            args.dockq,
            os.path.join(args.dir, f"{case}_pose{pose}.pdb"),
            os.path.join(args.dir, f"{case}_native.pdb"),
        )
        ours = {k: float(r[k]) for k in FIELDS}
        cells = []
        for k in FIELDS:
            d = abs(ours[k] - ref[k])
            if d > worst[k][0]:
                worst[k] = (d, f"{case}#{pose}")
            cells.append(f"{ours[k]:.3f} / {ref[k]:.3f}")
        extra = f"{float(r['exact_dockq']):.3f} / {float(r['best_dockq']):.3f}"
        print(f"| {case} | {pose} | " + " | ".join(cells) + f" | {extra} |")
        fixture.append(f"{case}\t{pose}\t{r['rot']}\t{r['trans']}\t" + "\t".join(f"{ref[k]:.6f}" for k in FIELDS))

    print()
    print("Largest absolute differences:")
    for k in FIELDS:
        d, where = worst[k]
        print(f"- {k}: {d:.2e}" + (f" ({where})" if where else ""))

    if args.fixture:
        with open(args.fixture, "w") as f:
            f.write("# Poses and official DockQ v2 values; generated by tools/benchmark/validate_dockq.py\n")
            f.write("\n".join(fixture) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
